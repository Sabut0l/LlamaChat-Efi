import re as _re_mod
import hashlib as _hashlib

_URL_RE = _re_mod.compile(r"(https?://\S+|www\.\S+|\S+@\S+\.\S+)")
_WS_RE = _re_mod.compile(r"\s+")

def _clean_turn(t):
    """Чистка реплики: ссылки/почта/лишние пробелы."""
    t = _URL_RE.sub("", str(t))
    t = _WS_RE.sub(" ", t).strip()
    return t

def _junk(t):
    """Мусор: реплика почти без букв (смайлы, цифры, знаки)."""
    letters = sum(ch.isalpha() for ch in t)
    return letters < max(2, len(t) // 4)

def polish(dialogs, dedup=True):
    """Чистка реплик, фильтр мусора, отсев «ответ = вопрос», дедупликация.
    Для персоны dedup=False: повторы шаблонов — намеренный вес."""
    out, seen = [], set()
    for d in dialogs:
        turns = [_clean_turn(t) for t in d]
        turns = [t for t in turns if t and not _junk(t)][:12]
        if len(turns) % 2 == 1:
            turns = turns[:-1]
        if len(turns) < 2:
            continue
        bad = False
        for i in range(0, len(turns) - 1, 2):
            if turns[i].lower() == turns[i + 1].lower():  # ответ повторяет вопрос
                bad = True
                break
        if bad:
            continue
        if dedup:
            h = _hashlib.md5(" | ".join(turns).lower().encode()).hexdigest()
            if h in seen:
                continue
            seen.add(h)
        out.append(turns)
    return out


