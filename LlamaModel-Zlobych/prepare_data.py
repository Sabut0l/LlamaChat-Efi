def render(turns, system=None):
    s = ""
    for i in range(0, len(turns) - 1, 2):
        u, a = turns[i], turns[i + 1]
        p = (f"[INST] <<SYS>>\n{system}\n<</SYS>>\n\n{u} [/INST]"
             if (i == 0 and system) else f"[INST] {u} [/INST]")
        s += p + " " + a + "\n"
    return s.strip()

def encode_dialog(sp, turns, system=None):
    # BOS(1) перед КАЖДЫМ [INST] и EOS(2) после каждого ответа — ровно так,
    # как кодирует инференс: run.c chat() и LlamaChat.c вызывают
    # Encode(..., bos=1, eos=0) на каждый ход, а не только на первый.
    # (Старый вариант с одним BOS на диалог давал расхождение: со второго
    # хода модель видела [2][1][INST] — в обучении так выглядела ГРАНИЦА
    # диалогов, и она «забывала» контекст и персону после первого ответа.)
    toks = []
    for i in range(0, len(turns) - 1, 2):
        u, a = turns[i].strip(), turns[i + 1].strip()
        if not (u and a):
            continue
        p = (f"[INST] <<SYS>>\n{system}\n<</SYS>>\n\n{u} [/INST]"
             if (i == 0 and system) else f"[INST] {u} [/INST]")
        toks += [1] + sp.encode(p) + sp.encode(" " + a) + [2]
    return toks

def stats(dialogs, title):
    """Само-проверка ПЕРЕД арендой GPU: видно, что маркеры реально в корпусе."""
    n = len(dialogs)
    def share(sub):
        k = sum(1 for d in dialogs if any(sub in t for t in d))
        return k, (100.0 * k / n if n else 0.0)
    print("--- %s: %d диалогов ---" % (title, n))
    for m in ("<CMD>exit</CMD>", "<CMD>askpass</CMD>", "<CMD>openfile</CMD>",
              "<CMD>sysinfo</CMD>", "(конфиг:", "(пароль верный)", "Злобыч"):
        k, p = share(m)
        print("    %-22s %7d  (%.2f%%)" % (m, k, p))


