def pick_text(ex):
    for k in ("text", "joke", "jokes", "content", "comment", "value"):
        v = ex.get(k)
        if isinstance(v, str) and v.strip():
            return v.strip()
    for v in ex.values():
        if isinstance(v, str) and v.strip():
            return v.strip()
    return ""

def extract_turns(ex):
    """Список реплик из записи любого популярного формата."""
    conv = ex.get("conversations") or ex.get("messages")
    # parquet/arrow часто хранит список сообщений как «словарь списков»:
    # {"role": [...], "content": [...]} — транспонируем обратно
    if isinstance(conv, dict):
        roles = conv.get("role") or conv.get("from") or []
        vals = conv.get("content") or conv.get("value") or []
        if isinstance(roles, list) and isinstance(vals, list) and len(roles) == len(vals):
            conv = [{"role": r, "content": v} for r, v in zip(roles, vals)]
    if isinstance(conv, list) and conv and isinstance(conv[0], dict):
        turns, expect = [], "user"
        for msg in conv:
            role = str(msg.get("from") or msg.get("role") or "").lower()
            val = str(msg.get("value") or msg.get("content") or "").strip()
            if not val or role == "system":
                continue
            r = "user" if role in ("human", "user", "prompter") else "assistant"
            if r == expect:
                turns.append(val)
                expect = "assistant" if r == "user" else "user"
        return turns
    for k in ("dialog", "dialogue", "utterances", "turns"):
        v = ex.get(k)
        if isinstance(v, list):
            return [str(t).strip() for t in v if str(t).strip()]
    for kq, ka in (("context","reply"), ("question","answer"),
                   ("prompt","response"), ("utterance","reply")):
        q, a = ex.get(kq), ex.get(ka)
        if q and a:
            return [str(q).strip(), str(a).strip()]
    return []

def collect_strings(obj, keys=("text", "jokes", "joke")):
    out = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k in keys:
                if isinstance(v, str):
                    out.append(v)
                elif isinstance(v, list):
                    out += [x for x in v if isinstance(x, str)]
                else:
                    out += collect_strings(v, keys)
            else:
                out += collect_strings(v, keys)
    elif isinstance(obj, list):
        for it in obj:
            out += collect_strings(it, keys)
    return out

